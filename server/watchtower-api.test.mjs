import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createApp} from './app.mjs';
import {canonicalJson,sha256} from './monitoring.mjs';
import {KAZAKHSTAN_SOURCES} from './kazakhstan-profile.mjs';

test('Kazakhstan auto profile collects public reports, exports provenance, and preserves pause on restart',async t=>{
  const folder=mkdtempSync(join(tmpdir(),'safenet-kz-api-'));
  const storePath=join(folder,'cases.json');let fetches=0;
  const watchtowerFetchPreview=async handle=>{fetches++;return `<div class="tgme_channel_info_header_title">Test official channel</div><div class="tgme_widget_message" data-post="${handle}/123"><div class="tgme_widget_message_text">Осторожно: мошенники обещают гарантированный доход. Не переводите деньги!</div><a class="tgme_widget_message_date" href="https://t.me/${handle}/123"><time datetime="2026-10-24T01:00:00Z"></time></a></div>`;};
  const options={storePath,seed:false,autoProfile:true,watchtowerFetchPreview,mediaService:{close:async()=>{}}};
  const app=createApp(options),server=app.listen(0,'127.0.0.1');
  await new Promise(resolve=>server.once('listening',resolve));
  t.after(async()=>{app.locals.watchtower.close();await new Promise(resolve=>server.close(resolve));rmSync(folder,{recursive:true,force:true});});
  const base=`http://127.0.0.1:${server.address().port}`;
  const send=(path,method,body,headers={})=>fetch(base+path,{method,headers:{'Content-Type':'application/json',...headers},body:JSON.stringify(body)});
  const initial=await(await fetch(base+'/api/watchtower')).json();
  assert.equal(initial.enabled,true);assert.equal(initial.intervalMinutes,10);assert.equal(initial.minScore,30);assert.equal(initial.sources.length,KAZAKHSTAN_SOURCES.length);assert.equal(initial.coverage.wholePlatform,false);
  assert.equal(fetches,0,'Creating an app alone does not start network I/O');
  assert.equal((await(await fetch(base+'/api/monitoring')).json()).enabled,true);
  assert.equal((await send('/api/watchtower','PUT',{enabled:false},{Origin:'https://attacker.example'})).status,403);
  assert.equal((await send('/api/watchtower','PUT',{enabled:false},{Origin:'chrome-extension://'+'a'.repeat(32)})).status,403);
  const collected=await(await send('/api/watchtower/run','POST',{})).json();
  assert.equal(fetches,KAZAKHSTAN_SOURCES.length);assert.equal(collected.stats.savedCases,KAZAKHSTAN_SOURCES.length);
  const {cases}=await(await fetch(base+'/api/cases')).json();
  assert.ok(cases.every(item=>item.riskContext==='warning_or_news'&&!item.demo));
  const bundle=await(await fetch(base+`/api/cases/${cases[0].id}/evidence`)).json();
  assert.equal(bundle.payload.collectionScope,'public_telegram_preview');
  assert.equal(bundle.integrity.digest,sha256(canonicalJson(bundle.payload)));
  assert.equal((await send('/api/watchtower/sources','POST',{platform:'telegram',handle:'http://127.0.0.1/'})).status,400);
  await send('/api/watchtower','PUT',{enabled:false});
  assert.equal((await send('/api/watchtower/run','POST',{})).status,409);
  const restarted=createApp(options);
  assert.equal(restarted.locals.watchtower.snapshot().enabled,false,'Existing pause is not overridden by automatic profile');
  restarted.locals.watchtower.close();
});
